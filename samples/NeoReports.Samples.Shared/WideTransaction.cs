namespace NeoReports.Samples.Shared;

/// <summary>
/// A deliberately wide report row (Epic H / D46) — a denormalized sales-transaction shape spanning
/// every scalar <c>ColumnType</c> the engine ships with an obvious CLR mapping (string, long,
/// decimal, bool, date-only, date-time, UTC timestamp, Guid), reused as-is by every Aspire multi-DB
/// sample (<see cref="WideTransactionGenerator"/> seeds it; each sample declares its own
/// <c>Col&lt;WideTransaction,_&gt;</c> report columns with the matching <c>ColumnType</c>).
/// </summary>
public sealed record WideTransaction(
    Guid TransactionId,
    long CustomerId,
    string CustomerName,
    string CustomerEmail,
    string CustomerCity,
    string CustomerCountry,
    bool IsVipCustomer,
    long ProductId,
    string ProductName,
    string ProductCategory,
    string ProductSku,
    long Quantity,
    decimal UnitPrice,
    decimal DiscountRate,
    decimal TaxRate,
    decimal ShippingCost,
    decimal ProcessingFee,
    decimal TotalAmount,
    string Currency,
    string PaymentMethod,
    bool IsRefunded,
    decimal RefundAmount,
    bool IsGift,
    string ShippingCity,
    string ShippingCountry,
    string ShippingPostalCode,
    string CarrierName,
    string TrackingNumber,
    long EstimatedDeliveryDays,
    DateTime OrderDate,
    DateTime ShippedDate,
    DateTime DeliveredDate,
    DateTime CreatedAt,
    DateTime UpdatedAt,
    DateTime ProcessedAtUtc,
    long SalesRepId,
    string SalesRepName,
    string Region,
    string Channel,
    string Campaign,
    string ReferralCode,
    string DeviceType,
    string Browser,
    string OperatingSystem,
    Guid SessionId,
    long Rating,
    decimal FeedbackScore,
    long LoyaltyPoints,
    bool IsFirstPurchase,
    long WarehouseId,
    string Notes);
